export function getDecodableWords(learnedPhonemes) {
  const set = new Set(learnedPhonemes);
  return WORD_BANK.filter(w => w.phonemes.every(p => set.has(p)));
}

export function getWordsForUnit(unitPhonemes, allLearnedPhonemes) {
  const allSet = new Set(allLearnedPhonemes);
  const unitSet = new Set(unitPhonemes);
  return WORD_BANK.filter(w => {
    const allKnown = w.phonemes.every(p => allSet.has(p));
    const usesNewPhoneme = w.phonemes.some(p => unitSet.has(p));
    return allKnown && usesNewPhoneme;
  });
}
